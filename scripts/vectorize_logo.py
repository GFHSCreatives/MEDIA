"""Trace the original GLOBAL logo PNG into clean vector layers.

Outputs src/logoPaths.ts with:
  - ARC: the orange horizon arc path
  - LETTERS: one path per letter (G, L, O, B, A, L)
  - ARC_STOPS: gradient colour stops sampled from the original artwork
Coordinates are in the original 599x416 pixel space (viewBox).
"""
import json
import sys
from pathlib import Path

import numpy as np
import potrace
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "global-logo-original.png"
OUT = ROOT / "src" / "logoPaths.ts"
UP = 8  # supersample factor before tracing

im = Image.open(SRC).convert("RGBA")
W, H = im.size
arr = np.asarray(im).astype(float)
r, g, b, a = (arr[..., i] for i in range(4))
alpha = a / 255.0

# Ink coverage per layer (soft masks so anti-aliasing is preserved through upscale)
orange_cov = np.clip((r - b - 40) / 80.0, 0, 1) * alpha
lum = (r + g + b) / 3.0
dark_cov = np.clip((200 - lum) / 150.0, 0, 1) * alpha * (orange_cov < 0.2)
dark_cov[:200, :] = 0          # letters live below the arc
dark_cov[:, 580:] = 0          # drop the stray vertical artefact at the right edge


def trace(cov, x0=0, x1=None):
    cov = cov.copy()
    if x1 is not None:
        m = np.zeros_like(cov)
        m[:, x0:x1] = cov[:, x0:x1]
        cov = m
    img = Image.fromarray((cov * 255).astype(np.uint8))
    img = img.resize((W * UP, H * UP), Image.BICUBIC).filter(ImageFilter.GaussianBlur(UP * 0.35))
    # potracer inverts its input (treats True as background), so pass the background mask
    bm = potrace.Bitmap(np.asarray(img) <= 127)
    plist = bm.trace(turdsize=40 * UP, alphamax=1.0, opticurve=True, opttolerance=0.2)
    d = []
    s = 1.0 / UP
    for curve in plist:
        st = curve.start_point
        d.append(f"M{st.x*s:.2f} {st.y*s:.2f}")
        for seg in curve.segments:
            if seg.is_corner:
                d.append(f"L{seg.c.x*s:.2f} {seg.c.y*s:.2f}L{seg.end_point.x*s:.2f} {seg.end_point.y*s:.2f}")
            else:
                d.append(
                    f"C{seg.c1.x*s:.2f} {seg.c1.y*s:.2f} {seg.c2.x*s:.2f} {seg.c2.y*s:.2f} {seg.end_point.x*s:.2f} {seg.end_point.y*s:.2f}"
                )
        d.append("Z")
    return "".join(d)


def fit_arc(cov):
    """Fit the crescent analytically: per-column centroid + thickness, then
    smooth polynomials. Gives perfectly clean edges at any resolution."""
    xs, cs, ts = [], [], []
    for x in range(W):
        col = cov[:, x]
        t = col.sum()
        if t > 0.6:
            yy = np.arange(H)
            xs.append(x + 0.5); cs.append((col * yy).sum() / t + 0.5); ts.append(t)
    xs, cs, ts = map(np.array, (xs, cs, ts))
    x0, x1 = xs.min() - 1.0, xs.max() + 1.0
    u = (xs - x0) / (x1 - x0)
    pc = np.polyfit(u, cs, 4)
    # thickness modelled as t(u) = sin(pi u)^p * poly(u) -> exactly zero at both tips
    base = np.sin(np.pi * u) ** 0.85
    pt = np.polyfit(u, ts / np.maximum(base, 1e-3), 3, w=base ** 2)
    uu = np.linspace(0, 1, 160)
    c = np.polyval(pc, uu)
    t = (np.sin(np.pi * uu) ** 0.85) * np.polyval(pt, uu)
    X = x0 + uu * (x1 - x0)
    top = [(X[i], c[i] - t[i] / 2) for i in range(len(uu))]
    bot = [(X[i], c[i] + t[i] / 2) for i in range(len(uu))][::-1]
    pts = top + bot[1:-1]
    d = "M" + "L".join(f"{px:.2f} {py:.2f}" for px, py in pts) + "Z"
    center = [[round(float(X[i]), 2), round(float(c[i]), 2), round(float(t[i]), 2)] for i in range(0, len(uu), 4)]
    return d, center


arc_d, arc_center = fit_arc(orange_cov)

# Letter segmentation by empty columns
cols = (dark_cov[200:340] > 0.3).any(0)
runs, start = [], None
for x, c in enumerate(cols):
    if c and start is None:
        start = x
    if not c and start is not None:
        runs.append((start, x)); start = None
if start is not None:
    runs.append((start, W))
runs = [rr for rr in runs if rr[1] - rr[0] > 10]
names = ["G", "L", "O", "B", "A", "L"]
assert len(runs) == 6, runs
letters = []
for (x0, x1), n in zip(runs, names):
    ys = np.nonzero((dark_cov[:, x0:x1] > 0.3).any(1))[0]
    letters.append({"char": n, "d": trace(dark_cov, max(0, x0 - 3), min(W, x1 + 3)),
                    "x0": x0, "x1": x1, "y0": int(ys.min()), "y1": int(ys.max())})

# Arc geometry + gradient stops sampled across its width
ys_o, xs_o = np.nonzero(orange_cov > 0.6)
ax0, ax1 = int(xs_o.min()), int(xs_o.max())
stops = []
centerline = arc_center
for t in np.linspace(0, 1, 9):
    x = int(ax0 + 4 + t * (ax1 - ax0 - 8))
    col = np.nonzero(orange_cov[:, x] > 0.8)[0]
    px = arr[col, x, :3].mean(0)
    stops.append({"offset": round(float(t), 3), "color": "#%02x%02x%02x" % tuple(int(v) for v in px)})
# tips are anti-aliased slivers; reuse the nearest solid sample for the end stops
stops[0]["color"], stops[-1]["color"] = stops[1]["color"], stops[-2]["color"]

ts = f"""// AUTO-GENERATED by scripts/vectorize_logo.py from assets/global-logo-original.png
// Do not edit by hand. Coordinates are in the original {W}x{H} artwork space.
export const LOGO_VIEWBOX = {{ width: {W}, height: {H} }};
export const ARC_PATH = {json.dumps(arc_d)};
export const ARC_BOUNDS = {{ x0: {ax0}, x1: {ax1}, y0: {int(ys_o.min())}, y1: {int(ys_o.max())} }};
export const ARC_STOPS: {{ offset: number; color: string }}[] = {json.dumps(stops)};
/** [x, y, thickness] samples along the arc's centre line (for flight paths & particles) */
export const ARC_CENTERLINE: [number, number, number][] = {json.dumps(centerline)};
export const LETTERS: {{ char: string; d: string; x0: number; x1: number; y0: number; y1: number }}[] = {json.dumps(letters, indent=1)};
export const INK = "#1a1a1a";
"""
OUT.write_text(ts)
print("wrote", OUT, "arc", ax0, ax1, "letters", [(l['char'], l['x0'], l['x1'], l['y0'], l['y1']) for l in letters])
print(stops)
